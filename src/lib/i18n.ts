const LANG_KEY = 'mboafit_lang';

export function getStoredLanguage(): AppLanguage {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'fr' || saved === 'en') return saved;
  // Auto-detect French if browser language starts with fr
  if (typeof navigator !== 'undefined' && navigator.language && navigator.language.startsWith('fr')) {
    return 'fr';
  }
  return 'en';
}

export function setStoredLanguage(lang: AppLanguage) {
  localStorage.setItem(LANG_KEY, lang);
  window.dispatchEvent(new CustomEvent('languagechange', { detail: lang }));
}

export function useI18n() {
  const [lang, setLang] = useState<AppLanguage>(getStoredLanguage());

  useEffect(() => {
    const handler = (e: Event) => {
      const customEvent = e as CustomEvent<AppLanguage>;
      if (customEvent.detail) {
        setLang(customEvent.detail);
      } else {
        setLang(getStoredLanguage());
      }
    };
    window.addEventListener('languagechange', handler);
    return () => window.removeEventListener('languagechange', handler);
  }, []);

  const t = (key: keyof typeof translations['en'], params?: Record<string, string | number>): string => {
    let text = translations[lang]?.[key] || translations['en'][key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      });
    }
    return text;
  };

  const changeLanguage = (newLang: AppLanguage) => {
    setStoredLanguage(newLang);
    setLang(newLang);
  };

  return { lang, t, setLanguage: changeLanguage };
}
